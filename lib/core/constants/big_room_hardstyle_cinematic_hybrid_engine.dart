  static bool matchesLane({
    String primaryGenre = '',
    String subGenreFusion = '',
  }) {
    final blob = _genreBlob(primaryGenre, subGenreFusion);
    if (blob.trim().isEmpty) return false;
    return _laneMarkers.any(blob.contains);
  }

  static bool matchesInput(UserInputModel input) => matchesLane(
        primaryGenre: input.primaryGenre,
        subGenreFusion: input.subGenreFusion,
